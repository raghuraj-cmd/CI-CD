package com.experiment.ci.contract;

import au.com.dius.pact.provider.junit5.HttpTestTarget;
import au.com.dius.pact.provider.junit5.PactVerificationContext;
import au.com.dius.pact.provider.junit5.PactVerificationInvocationContextProvider;
import au.com.dius.pact.provider.junitsupport.Provider;
import au.com.dius.pact.provider.junitsupport.State;
import au.com.dius.pact.provider.junitsupport.loader.PactFolder;
import com.experiment.ci.model.Product;
import com.experiment.ci.repository.ProductRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.TestTemplate;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

/**
 * CONTRACT TESTS - Pact Provider Verification Side
 * ==================================================
 * Verifies that the real Spring Boot service implementation satisfies
 * the contract (Pact file) generated by the consumer tests.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@Provider("product-api")
@PactFolder("target/pacts")
@ActiveProfiles("test")
@DisplayName("Product API - Provider Contract Verification")
class ProductProviderContractTest {

    @LocalServerPort
    private int port;

    @Autowired
    private ProductRepository productRepository;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @BeforeEach
    void setup(PactVerificationContext context) {
        if (context != null) {
            context.setTarget(new HttpTestTarget("localhost", port));
        }
    }

    @TestTemplate
    @ExtendWith(PactVerificationInvocationContextProvider.class)
    void pactVerificationTestTemplate(PactVerificationContext context) {
        if (context != null) {
            context.verifyInteraction();
        }
    }

    @State("products exist in the system")
    void toProductsExistState() {
        productRepository.deleteAll();
        productRepository.save(Product.builder()
            .name("Laptop")
            .category("Electronics")
            .price(999.99)
            .stock(10)
            .description("High-end laptop")
            .build());
    }

    @State("a product with id 1 exists")
    void toProductOneExistsState() {
        productRepository.deleteAll();
        try {
            jdbcTemplate.execute("ALTER TABLE products ALTER COLUMN id RESTART WITH 1");
        } catch (Exception ignored) {}

        productRepository.save(Product.builder()
            .name("Laptop")
            .category("Electronics")
            .price(999.99)
            .stock(10)
            .description("High-end laptop")
            .build());
    }

    @State("product creation is available")
    void toProductCreationAvailableState() {
        productRepository.findByNameIgnoreCase("Test Product")
            .ifPresent(p -> productRepository.delete(p));
    }

    @State("service is running")
    void toServiceIsRunningState() {
        // Health check endpoint responds independently
    }
}
